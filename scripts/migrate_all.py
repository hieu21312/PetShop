def dong_bo_du_lieu():
    kn_sql, kn_pg = ket_noi_csdl()
    con_tro_sql = kn_sql.cursor()

    con_tro_sql.execute("SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE='BASE TABLE' ORDER BY TABLE_NAME;")
    ds_bang = [dong[0] for dong in con_tro_sql.fetchall()]
    print(f"Tim thay {len(ds_bang)} bang can chuyen.")

    con_tro_sql.execute('''
    SELECT t.name, c.name
    FROM sys.indexes i
    JOIN sys.index_columns ic ON i.object_id = ic.object_id AND i.index_id = ic.index_id
    JOIN sys.columns c ON ic.object_id = c.object_id AND ic.column_id = c.column_id
    JOIN sys.tables t ON i.object_id = t.object_id
    WHERE i.is_primary_key = 1
    ORDER BY t.name, ic.key_ordinal
    ''')
    khoa_chinh = {}
    for ten_b, ten_c in con_tro_sql.fetchall():
        khoa_chinh.setdefault(ten_b, []).append(ten_c)

    con_tro_sql.execute('''
    SELECT t.name, c.name, ty.name, c.max_length, c.is_identity, c.is_nullable
    FROM sys.tables t
    JOIN sys.columns c ON t.object_id = c.object_id
    JOIN sys.types ty ON c.user_type_id = ty.user_type_id
    ORDER BY t.name, c.column_id
    ''')
    thong_tin_cot = {}
    cot_tu_tang = {}
    for ten_b, ten_c, kieu_c, do_dai_c, tu_tang, cho_phep_null in con_tro_sql.fetchall():
        thong_tin_cot.setdefault(ten_b, []).append((ten_c, kieu_c, do_dai_c, tu_tang, cho_phep_null))
        if tu_tang:
            cot_tu_tang.setdefault(ten_b, []).append(ten_c)

    print("Xoa cac bang cu tren PostgreSQL...")
    for ten_b in ds_bang:
        kn_pg.run(f'DROP TABLE IF EXISTS "{ten_b.lower()}" CASCADE;')

    print("Tao cau truc bang moi tren PostgreSQL...")
    for ten_b in ds_bang:
        ds_cot = thong_tin_cot[ten_b]
        ds_khoa = khoa_chinh.get(ten_b, [])
        dinh_nghia_cot = []
        for ten_c, kieu_c, do_dai_c, tu_tang, cho_phep_null in ds_cot:
            kieu_pg = chuyen_kieu_du_lieu(kieu_c, do_dai_c, tu_tang)
            not_null = "NOT NULL" if not cho_phep_null and not tu_tang else ""
            dinh_nghia_cot.append(f'"{ten_c.lower()}" {kieu_pg} {not_null}'.strip())

        cau_lenh_pk = ""
        if ds_khoa:
            cot_pk = ", ".join([f'"{k.lower()}"' for k in ds_khoa])
            cau_lenh_pk = f', CONSTRAINT "pk_{ten_b.lower()}" PRIMARY KEY ({cot_pk})'

        sql_tao_bang = f'CREATE TABLE "{ten_b.lower()}" (\n  ' + ",\n  ".join(dinh_nghia_cot) + cau_lenh_pk + '\n);'
        kn_pg.run(sql_tao_bang)

    print("Bat dau sao chep du lieu...")
    tong_so_dong = 0

    for ten_b in ds_bang:
        ds_cot = thong_tin_cot[ten_b]
        chuoi_cot_sql = ", ".join([f'[{c[0]}]' for c in ds_cot])
        chuoi_cot_pg = ", ".join([f'"{c[0].lower()}"' for c in ds_cot])
        tham_so = ", ".join([f':p{i}' for i in range(len(ds_cot))])

        con_tro_sql.execute(f"SELECT {chuoi_cot_sql} FROM [{ten_b}]")
        cac_dong = con_tro_sql.fetchall()

        sql_chen = f'INSERT INTO "{ten_b.lower()}" ({chuoi_cot_pg}) VALUES ({tham_so})'

        for dong in cac_dong:
            gia_tri_chen = {}
            for i, gia_tri in enumerate(dong):
                if isinstance(gia_tri, bytearray):
                    gia_tri_chen[f'p{i}'] = bytes(gia_tri)
                elif isinstance(gia_tri, (int, float, str, bytes)) or gia_tri is None:
                    gia_tri_chen[f'p{i}'] = gia_tri
                else:
                    gia_tri_chen[f'p{i}'] = str(gia_tri) if gia_tri is not None else None
            kn_pg.run(sql_chen, **gia_tri_chen)

        for cot_id in cot_tu_tang.get(ten_b, []):
            try:
                kn_pg.run(f'''
                SELECT setval(
                    pg_get_serial_sequence('"{ten_b.lower()}"', '{cot_id.lower()}'),
                    COALESCE((SELECT MAX("{cot_id.lower()}") FROM "{ten_b.lower()}"), 0) + 1,
                    false
                );
                ''')
            except Exception:
                pass

        so_dong_bang = len(cac_dong)
        tong_so_dong += so_dong_bang
        print(f"  + Da chuyen bang {ten_b}: {so_dong_bang} dong")

    print(f"Xong! Tong cong da chuyen {len(ds_bang)} bang, {tong_so_dong} dong du lieu.")

    kn_sql.close()
    kn_pg.close()

if __name__ == '__main__':
    dong_bo_du_lieu()
