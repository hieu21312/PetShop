def chuyen_kieu_du_lieu(kieu_goc, do_dai, la_khoa_tu_tang):
    if la_khoa_tu_tang:
        if kieu_goc == 'bigint':
            return 'BIGINT GENERATED BY DEFAULT AS IDENTITY'
        return 'INTEGER GENERATED BY DEFAULT AS IDENTITY'

    kieu = kieu_goc.lower()
    if kieu == 'int':
        return 'INTEGER'
    elif kieu in ('smallint', 'tinyint'):
        return 'SMALLINT'
    elif kieu == 'bigint':
        return 'BIGINT'
    elif kieu in ('decimal', 'numeric', 'money', 'smallmoney'):
        return 'NUMERIC(18,2)'
    elif kieu in ('float', 'real'):
        return 'DOUBLE PRECISION'
    elif kieu == 'bit':
        return 'BOOLEAN'
    elif kieu == 'date':
        return 'DATE'
    elif kieu in ('datetime', 'datetime2', 'smalldatetime'):
        return 'TIMESTAMP'
    elif kieu == 'time':
        return 'TIME'
    elif kieu in ('nvarchar', 'nchar'):
        so_ky_tu = do_dai // 2 if do_dai > 0 else -1
        if 0 < so_ky_tu <= 1000:
            return f'VARCHAR({so_ky_tu})'
        return 'TEXT'
    elif kieu in ('varchar', 'char'):
        if 0 < do_dai <= 2000:
            return f'VARCHAR({do_dai})'
        return 'TEXT'
    elif kieu in ('varbinary', 'binary', 'image'):
        return 'BYTEA'
    elif kieu == 'uniqueidentifier':
        return 'UUID'
    else:
        return 'TEXT'

